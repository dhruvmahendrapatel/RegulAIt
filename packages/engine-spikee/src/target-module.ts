/**
 * ADR-0245 — THE ONE SPIKEE TARGET THIS BUILD RUNS: a workspace module (`targets/regulait_gateway.py`, spikee's own
 * extension point: `spikee test --target <name>` loads `<cwd>/targets/<name>.py` before any built-in target).
 *
 * Why a module of our own, and not spikee's built-in `llm_provider` target: every built-in LLM path goes through
 * `spikee.utilities.llm.get_llm` and any-llm's provider registry (openai, bedrock, ...), which takes the provider's
 * hosted endpoint and key from the environment (or a `.env` file) and offers no per-request header setting. This
 * module is the narrowest path that meets the invariant (config.ts `assertGatewayOnly`):
 *
 *   - ONE endpoint: `<gateway /v1>/chat/completions`, read from `regulait_gateway.json` beside it (written by the
 *     worker, checked before it is written); the run's key only from the environment variable SPIKEE_KEY_ENV;
 *   - the gateway's own `x-regulait-*` headers and nothing else (no user agent override, no vendor header);
 *   - Python's standard library only (`urllib.request`), with NO proxy handler (an inherited proxy can never reroute a
 *     call), and redirects REFUSED (a 3xx is an error, never followed to another host);
 *   - an answer bounded before it is parsed; a reply that is not one text message raises, so spikee records the entry
 *     with an `error` and the mapper reads it as unknown, never pass.
 * It never imports any-llm, a provider, dotenv or a judge.
 */
/** the one env var the run's key travels in (read only by the module above) */
export const SPIKEE_KEY_ENV = "REGULAIT_SPIKEE_API_KEY";
export const SPIKEE_TARGET_NAME = "regulait_gateway";
export const SPIKEE_TARGET_MODULE_FILE = `${SPIKEE_TARGET_NAME}.py`;
export const SPIKEE_TARGET_CONFIG_FILE = `${SPIKEE_TARGET_NAME}.json`;
/** the largest gateway answer the module reads (a chat completion is far smaller) */
export const SPIKEE_TARGET_MAX_ANSWER_BYTES = 4 * 1024 * 1024;

export const SPIKEE_TARGET_MODULE = `"""RegulAIt gateway target for spikee (generated by @regulait/engine-spikee; ADR-0245). Do not edit."""
import json
import os
import urllib.request

from spikee.templates.target import Target

_HERE = os.path.dirname(os.path.abspath(__file__))
_MAX_ANSWER = ${SPIKEE_TARGET_MAX_ANSWER_BYTES}


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise ValueError("the gateway answered with a redirect; it is never followed")


_OPENER = urllib.request.build_opener(urllib.request.ProxyHandler({}), _NoRedirect())


class RegulaitGatewayTarget(Target):
    def get_description(self):
        return [], "The RegulAIt gateway's OpenAI-compatible chat route (the run's virtual key)."

    def get_available_option_values(self):
        return [], False

    def process_input(self, input_text: str, system_message: str | None = None):
        with open(os.path.join(_HERE, "${SPIKEE_TARGET_CONFIG_FILE}"), encoding="utf-8") as f:
            conf = json.load(f)
        key = os.environ["${SPIKEE_KEY_ENV}"]
        messages = []
        if system_message:
            messages.append({"role": "system", "content": system_message})
        messages.append({"role": "user", "content": input_text})
        body = json.dumps({"model": conf["model"], "messages": messages}).encode("utf-8")
        headers = {"content-type": "application/json", "accept": "application/json", "authorization": "Bearer " + key}
        for name, value in conf["headers"].items():
            headers[name] = value
        req = urllib.request.Request(conf["url"], data=body, headers=headers, method="POST")
        with _OPENER.open(req, timeout=conf["timeout"]) as resp:
            raw = resp.read(_MAX_ANSWER + 1)
        if len(raw) > _MAX_ANSWER:
            raise ValueError("the gateway's answer is over the size bound")
        data = json.loads(raw.decode("utf-8"))
        content = data["choices"][0]["message"]["content"]
        if not isinstance(content, str):
            raise ValueError("the gateway's answer holds no text reply")
        return content
`;
