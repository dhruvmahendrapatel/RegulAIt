/**
 * The endpoint agent's compiled key patterns against the shared source (R15 §2.3, ADR-0195 decision 11).
 *
 *   node agents/endpoint/scripts/check-secret-rules.mjs           exit 1 on drift, else 0
 *   node agents/endpoint/scripts/check-secret-rules.mjs --write   rewrite testdata/rules.json
 *
 * Needs packages/shared built (`pnpm --filter @regulait/shared build`). It checks two things:
 *   1. the shared `dlp.secret.*` credential rules (ids, and a SHA-256 of each rule's source and flags) equal
 *      internal/secrets/testdata/rules.json. A changed or added shared rule fails here until the Go table is
 *      updated by hand (an RE2 rewrite may be needed) and the file is regenerated with --write;
 *   2. every vector in internal/secrets/testdata/vectors.json gives the same rule ids under the shared
 *      JavaScript RegExps as it must under the Go table (secrets_test.go runs the Go side).
 * Only digests are written, never a pattern's source, so the file holds nothing key-shaped.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "../../..");
const testdata = path.join(here, "../internal/secrets/testdata");
const rulesFile = path.join(testdata, "rules.json");

const { CREDENTIAL_MATERIAL_RULES } = await import(pathToFileURL(path.join(repo, "packages/shared/dist/index.js")).href);
const shared = CREDENTIAL_MATERIAL_RULES.filter((r) => r.id.startsWith("dlp.secret."));
const recorded = shared.map((r) => ({ id: r.id, sourceSha256: createHash("sha256").update(`${r.re.source}/${r.re.flags}`).digest("hex") }));

if (process.argv.includes("--write")) {
  writeFileSync(rulesFile, `${JSON.stringify({ comment: "Generated by scripts/check-secret-rules.mjs --write from packages/shared CREDENTIAL_MATERIAL_RULES.", rules: recorded }, null, 1)}\n`);
  console.log(`wrote ${recorded.length} rules`);
  process.exit(0);
}

let failed = false;
const onDisk = JSON.parse(readFileSync(rulesFile, "utf8")).rules;
if (JSON.stringify(onDisk) !== JSON.stringify(recorded)) {
  failed = true;
  console.error("shared dlp.secret.* rules differ from internal/secrets/testdata/rules.json:");
  for (const r of recorded) {
    const d = onDisk.find((x) => x.id === r.id);
    if (!d) console.error(`  added in shared: ${r.id}`);
    else if (d.sourceSha256 !== r.sourceSha256) console.error(`  changed in shared: ${r.id}`);
  }
  for (const d of onDisk) if (!recorded.some((r) => r.id === d.id)) console.error(`  removed from shared: ${d.id}`);
  console.error("Update internal/secrets/secrets.go (RE2) to match, then run with --write.");
}

const { vectors } = JSON.parse(readFileSync(path.join(testdata, "vectors.json"), "utf8"));
for (const v of vectors) {
  const input = v.parts.map((p) => (p.lit ?? "") + (p.rep ? p.rep.repeat(p.n) : "")).join("");
  const got = shared.filter((r) => {
    r.re.lastIndex = 0;
    const hit = r.re.test(input);
    r.re.lastIndex = 0;
    return hit;
  }).map((r) => r.id);
  if (JSON.stringify(got) !== JSON.stringify(v.expect)) {
    failed = true;
    console.error(`vector "${v.name}": shared rules give ${JSON.stringify(got)}, expected ${JSON.stringify(v.expect)}`);
  }
}
if (failed) process.exit(1);
console.log(`ok: ${recorded.length} rules, ${vectors.length} vectors agree with packages/shared`);
