/**
 * ADR-0195 SD2 phase B: the `cloud_aws`, `cloud_gcp` and `cloud_azure` scanners, registered against SD0's
 * `Scanner` interface (`discovery-scanners.ts`). The cloud work itself lives in `@regulait/cloud-discovery`; this
 * file only translates a discovery source (target, scope, credential) into an adapter's configuration, wires the
 * worker's hooks into it, and maps what the adapter saw onto `ScanObservation`s.
 *
 * WIRING (SD0 contract):
 *  - network: every SDK call goes through `ctx.fetch` (the egress-guarded fetch), wrapped so each request first
 *    awaits `ctx.throttle()`, retries a 429/503 only when `ctx.backoff(res)` says so, and feeds every response body
 *    to `ctx.recordRaw()` (digested, never kept);
 *  - people: calling principals go through `ctx.pseudonymise("cloud_principal", ...)` before an observation exists;
 *  - lease: the adapters call `ctx.heartbeat()` between regions, projects and subscriptions and stop on false;
 *  - result: observations only, each carrying `artifact: { kind: "cloud_ai_service", value: <service key> }` so the
 *    worker matches it against the admin catalogue (detection is data).
 *
 * WHAT A CLOUD SOURCE LOOKS LIKE (key=value fields; documented in docs/deployment/CLOUD_DISCOVERY.md):
 *  - cloud_aws    target: accountId, stsRegion?, trailBucket?, trailBucketRegion?, trailPrefix?
 *                 scope: include = regions; organisation-level = every region the account has enabled
 *                 credential: federated publicConfig roleArn (AssumeRoleWithWebIdentity, audience sts.amazonaws.com);
 *                             externalId is generated by SD0. Static secret: JSON {accessKeyId, secretAccessKey,
 *                             sessionToken?} (the key id is not public config: SD0 refuses key-shaped names there)
 *  - cloud_gcp    target: projectId?, assetScope? (organizations/N or folders/N)
 *                 scope: include = project ids; organisation-level needs assetScope
 *                 credential: federated publicConfig projectNumber, workloadIdentityPool, workloadIdentityProvider,
 *                             serviceAccountEmail (impersonated); static secret: the key file JSON
 *  - cloud_azure  target: tenantId, managementGroupId?, logAnalyticsWorkspaceIds? (comma-separated), authorityHost?
 *                 scope: include = subscription ids; organisation-level needs managementGroupId
 *                 credential: publicConfig tenantId, clientId (both modes); static secret: the client secret
 *  Public config keys and shapes are SD0's allowlist (`DISCOVERY_PUBLIC_CONFIG` in @regulait/shared).
 *
 * FEDERATION IS PENDING. A federated credential needs an OIDC token minted by RegulAIt's ADR-0188 issuer for the
 * cloud's audience, signed RS256 (the one algorithm AWS, GCP and Entra all accept; ADR-0195 SD2 notes). The issuer
 * signs with Ed25519 only today, and adding the RS256 federation key is key material and schema this slice does
 * not own. Until `oidcToken` is supplied, a federated run fails with an explicit reason instead of guessing; the
 * static relaxation runs end to end. (AWS AssumeRole with the SD0-generated external id would need RegulAIt's own
 * AWS principal; it is not offered: SD0's public config for `cloud_aws` is the role ARN only.)
 *
 * WHAT COULD NOT BE READ. The adapters report every read's status; it is returned as SD0's `readOutcomes` (stored
 * with the run). When no read succeeded at all the run fails with the per-read summary as its error.
 */
import {
  AwsCloudScanner,
  AzureCloudScanner,
  GcpCloudScanner,
  DEFAULT_AUDIT_LOOKBACK_DAYS,
  DEFAULT_MAX_PAGES_PER_CALL,
  type AwsCredentialInput,
  type AzureCredentialInput,
  type CapabilityReport,
  type CloudObservation,
  type CloudScanner,
  type GcpCredentialInput,
  type OidcTokenSupplier,
} from "@regulait/cloud-discovery";
import { DISCOVERY_READ_OUTCOMES_MAX, type DiscoveryReadOutcome, type DiscoverySourceKind } from "@regulait/shared";
import type { ScanContext, ScanObservation, Scanner } from "./discovery-scanners.js";

export interface CloudScannerOptions {
  /** mints a federation token for an audience (ADR-0188 issuer, RS256); absent until the federation key exists */
  oidcToken?: OidcTokenSupplier;
}

/** a configuration problem a run can name without leaking anything */
export class CloudSourceConfigError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "CloudSourceConfigError";
  }
}

const FEDERATION_PENDING =
  "federated cloud credentials need RegulAIt's RS256 federation token from the ADR-0188 issuer, which is not configured yet (ADR-0195 SD2, pending); use a static credential (a relaxation) meanwhile";

function need(map: Readonly<Record<string, string>>, key: string, what: string): string {
  const v = map[key]?.trim();
  if (!v) throw new CloudSourceConfigError(`${what}: '${key}' is required`);
  return v;
}

function parseJsonSecret(secret: string | null, what: string): Record<string, unknown> {
  if (!secret) throw new CloudSourceConfigError(`${what}: the static credential has no secret`);
  try {
    const v: unknown = JSON.parse(secret);
    if (v && typeof v === "object" && !Array.isArray(v)) return v as Record<string, unknown>;
  } catch {
    // fall through: never echo the secret
  }
  throw new CloudSourceConfigError(`${what}: the static secret must be a JSON object`);
}

/**
 * The worker's hooks around `ctx.fetch`: throttle first, honour backoff, and (for the scan fetch only) digest every
 * body. `digest: false` builds the credential fetch: token-exchange responses carry credentials and are never fed to
 * the digest (review of #404, finding 3).
 */
export function scannerFetch(ctx: Pick<ScanContext, "fetch" | "throttle" | "backoff" | "recordRaw">, opts: { digest?: boolean } = {}): typeof fetch {
  const digest = opts.digest ?? true;
  const wrapped = async (input: string | URL | Request, init?: RequestInit): Promise<Response> => {
    for (;;) {
      await ctx.throttle();
      const res = await ctx.fetch(input, init);
      if ((res.status === 429 || res.status === 503) && (await ctx.backoff(res))) continue;
      if (digest) await digestBounded(res, ctx.recordRaw);
      return res;
    }
  };
  return wrapped as typeof fetch;
}

/** at most this much of one response body is digested (review of #404, finding 2) */
export const RAW_DIGEST_MAX_BYTES = 4 * 1024 * 1024;

/**
 * Feed a response body to the digest without holding more than the cap: a declared length over the cap is recorded
 * as a marker only; otherwise a clone is streamed chunk by chunk and abandoned once the cap is passed.
 */
export async function digestBounded(res: Response, recordRaw: (chunk: string | Uint8Array) => void, max = RAW_DIGEST_MAX_BYTES): Promise<void> {
  const declared = Number(res.headers.get("content-length") ?? "");
  if (Number.isFinite(declared) && declared > max) {
    recordRaw(`[body of ${declared} bytes over the ${max}-byte digest cap: not digested]`);
    return;
  }
  const body = res.clone().body;
  if (!body) return;
  const reader = body.getReader();
  let seen = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) return;
    seen += value.byteLength;
    if (seen > max) {
      recordRaw(`[body truncated at the ${max}-byte digest cap]`);
      // not awaited: cancelling one branch of a tee'd body settles only when the other branch is cancelled too,
      // and the caller still owns the other branch
      void reader.cancel().catch(() => undefined);
      return;
    }
    recordRaw(value);
  }
}

function awsCredential(ctx: ScanContext, opts: CloudScannerOptions): AwsCredentialInput {
  const c = ctx.credential!;
  if (c.mode === "static") {
    const s = parseJsonSecret(c.secret, "cloud_aws");
    const accessKeyId = typeof s.accessKeyId === "string" ? s.accessKeyId : "";
    const secretAccessKey = typeof s.secretAccessKey === "string" ? s.secretAccessKey : "";
    if (!accessKeyId || !secretAccessKey) throw new CloudSourceConfigError("cloud_aws: the static secret needs accessKeyId and secretAccessKey");
    return { mode: "aws_static", accessKeyId, secretAccessKey, ...(typeof s.sessionToken === "string" ? { sessionToken: s.sessionToken } : {}) };
  }
  const roleArn = need(c.publicConfig, "roleArn", "cloud_aws");
  if (!opts.oidcToken) throw new CloudSourceConfigError(FEDERATION_PENDING);
  return { mode: "aws_web_identity", roleArn };
}

function gcpCredential(ctx: ScanContext, opts: CloudScannerOptions): GcpCredentialInput {
  const c = ctx.credential!;
  if (c.mode === "static") {
    if (!c.secret) throw new CloudSourceConfigError("cloud_gcp: the static credential has no secret");
    return { mode: "gcp_service_account_key", keyJson: c.secret };
  }
  const projectNumber = need(c.publicConfig, "projectNumber", "cloud_gcp");
  const pool = need(c.publicConfig, "workloadIdentityPool", "cloud_gcp");
  const provider = need(c.publicConfig, "workloadIdentityProvider", "cloud_gcp");
  const serviceAccountEmail = need(c.publicConfig, "serviceAccountEmail", "cloud_gcp");
  if (!opts.oidcToken) throw new CloudSourceConfigError(FEDERATION_PENDING);
  return { mode: "gcp_workload_identity", audience: gcpWifAudience(projectNumber, pool, provider), serviceAccountEmail };
}

function azureCredential(ctx: ScanContext, opts: CloudScannerOptions): AzureCredentialInput {
  const c = ctx.credential!;
  const tenantId = need(c.publicConfig, "tenantId", "cloud_azure");
  const clientId = need(c.publicConfig, "clientId", "cloud_azure");
  if (c.mode === "static") {
    if (!c.secret) throw new CloudSourceConfigError("cloud_azure: the static credential has no secret");
    return { mode: "azure_client_secret", tenantId, clientId, clientSecret: c.secret };
  }
  if (!opts.oidcToken) throw new CloudSourceConfigError(FEDERATION_PENDING);
  return { mode: "azure_federated", tenantId, clientId };
}

const list = (v: string | undefined): string[] => (v ?? "").split(",").map((x) => x.trim()).filter(Boolean);

/** build the adapter for one run; exported for tests */
export function buildCloudScanner(kind: DiscoverySourceKind, ctx: ScanContext, fetchImpl: typeof fetch, opts: CloudScannerOptions, credentialFetch?: typeof fetch): CloudScanner {
  // every short-lived credential the adapter obtains or sends is registered for scrubbing (SD0 registerSecret)
  const credFetch = { ...(credentialFetch ? { credentialFetch } : {}), onSecret: (v: string) => ctx.registerSecret(v) };
  const t = ctx.source.target;
  const scope = ctx.source.scope;
  const oidc = opts.oidcToken ? { oidcToken: opts.oidcToken } : {};
  switch (kind) {
    case "cloud_aws": {
      const credential = awsCredential(ctx, opts);
      const trailBucket = t.trailBucket
        ? { trailBucket: { bucket: t.trailBucket, region: need(t, "trailBucketRegion", "cloud_aws"), ...(t.trailPrefix ? { prefix: t.trailPrefix } : {}) } }
        : {};
      return new AwsCloudScanner(
        {
          accountId: need(t, "accountId", "cloud_aws"),
          ...(scope.orgLevel ? {} : { regions: [...scope.include] }),
          ...(t.stsRegion ? { stsRegion: t.stsRegion } : {}),
          ...trailBucket,
        },
        { fetch: fetchImpl, ...credFetch, credential, ...oidc },
      );
    }
    case "cloud_gcp": {
      const credential = gcpCredential(ctx, opts);
      if (scope.orgLevel && !t.assetScope) throw new CloudSourceConfigError("cloud_gcp: an organisation-level scope needs 'assetScope' (organizations/N or folders/N)");
      const projectIds = scope.include.length ? [...scope.include] : t.projectId ? [t.projectId] : [];
      if (!projectIds.length && !scope.orgLevel) throw new CloudSourceConfigError("cloud_gcp: name at least one project");
      return new GcpCloudScanner({ projectIds, ...(scope.orgLevel && t.assetScope ? { assetScope: t.assetScope } : {}) }, { fetch: fetchImpl, ...credFetch, credential, ...oidc });
    }
    case "cloud_azure": {
      const credential = azureCredential(ctx, opts);
      if (scope.orgLevel && !t.managementGroupId) throw new CloudSourceConfigError("cloud_azure: an organisation-level scope needs 'managementGroupId'");
      const workspaces = list(t.logAnalyticsWorkspaceIds);
      return new AzureCloudScanner(
        {
          subscriptionIds: [...scope.include],
          ...(scope.orgLevel && t.managementGroupId ? { managementGroupId: t.managementGroupId } : {}),
          ...(workspaces.length ? { logAnalyticsWorkspaceIds: workspaces } : {}),
          ...(t.authorityHost ? { authorityHost: t.authorityHost } : {}),
        },
        { fetch: fetchImpl, ...credFetch, credential, ...oidc },
      );
    }
    default:
      throw new CloudSourceConfigError(`not a cloud source kind: ${kind}`);
  }
}

/** an adapter observation in SD0's terms */
export function toScanObservation(o: CloudObservation): ScanObservation {
  return {
    evidenceKind: o.signalSource,
    subjectKind: o.subjectKind,
    subject: o.subject,
    ...(o.lastSeen ? { observedAt: o.lastSeen } : {}),
    ...(o.callCount !== undefined ? { count: o.callCount } : {}),
    artifact: { kind: "cloud_ai_service", value: o.serviceKey },
  };
}

/** the pool provider resource name GCP workload identity federation takes as its audience */
export function gcpWifAudience(projectNumber: string, pool: string, provider: string): string {
  return `//iam.googleapis.com/projects/${projectNumber}/locations/global/workloadIdentityPools/${pool}/providers/${provider}`;
}

/**
 * The adapters' per-read report as SD0's `readOutcomes` (stored with the run, shown as "could not read: ..."):
 * one row per read, `read` named `<capability>@<scope>`, at most DISCOVERY_READ_OUTCOMES_MAX rows. Reads that did
 * not succeed come first, so a truncated list still shows every problem it can.
 */
export function toReadOutcomes(caps: readonly CapabilityReport[]): DiscoveryReadOutcome[] {
  const rows = caps.map((c): DiscoveryReadOutcome => {
    const read = `${c.capability}${c.scope ? `@${c.scope}` : ""}`.slice(0, 200);
    const detail = c.detail ?? (c.status === "read" && c.items !== undefined ? `${c.items} item(s)` : undefined);
    return { read, status: c.status, ...(detail ? { detail: detail.slice(0, 500) } : {}) };
  });
  const bad = rows.filter((r) => r.status !== "read");
  const good = rows.filter((r) => r.status === "read");
  return [...bad, ...good].slice(0, DISCOVERY_READ_OUTCOMES_MAX);
}

const NETWORK_FREE = new Set<CapabilityReport["status"]>(["skipped", "not_enabled"]);

/** "aws.bedrock.agents@us-east-1: denied (AccessDeniedException ...)" for every read that did not succeed */
export function capabilitySummary(caps: readonly CapabilityReport[], max = 12): string {
  const bad = caps.filter((c) => c.status !== "read");
  const shown = bad.slice(0, max).map((c) => `${c.capability}${c.scope ? `@${c.scope}` : ""}: ${c.status}${c.detail ? ` (${c.detail.slice(0, 160)})` : ""}`);
  return shown.join("; ") + (bad.length > shown.length ? `; and ${bad.length - shown.length} more` : "");
}

export function cloudScanner(kind: "cloud_aws" | "cloud_gcp" | "cloud_azure", opts: CloudScannerOptions = {}): Scanner {
  return {
    kind,
    requiresCredential: true,
    run: async (ctx) => {
      const adapter = buildCloudScanner(kind, ctx, scannerFetch(ctx), opts, scannerFetch(ctx, { digest: false }));
      const res = await adapter.scan({
        now: new Date(),
        auditLookbackDays: DEFAULT_AUDIT_LOOKBACK_DAYS,
        maxPagesPerCall: DEFAULT_MAX_PAGES_PER_CALL,
        pseudonymise: (p) => ctx.pseudonymise("cloud_principal", p.rawIdentifier),
        signal: ctx.signal,
        heartbeat: ctx.heartbeat,
      });
      ctx.recordRaw(JSON.stringify(res.capabilities));
      const attempted = res.capabilities.filter((c) => !NETWORK_FREE.has(c.status));
      if (attempted.length > 0 && !attempted.some((c) => c.status === "read")) {
        throw new Error(`no cloud read succeeded: ${capabilitySummary(res.capabilities)}`);
      }
      return { observations: res.observations.map(toScanObservation), readOutcomes: toReadOutcomes(res.capabilities) };
    },
  };
}

/** the three cloud scanners for `DISCOVERY_SCANNERS` */
export function cloudDiscoveryScanners(opts: CloudScannerOptions = {}): Scanner[] {
  return [cloudScanner("cloud_aws", opts), cloudScanner("cloud_gcp", opts), cloudScanner("cloud_azure", opts)];
}
